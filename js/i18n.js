function translate(lang, key) {
  return key.split(".").reduce(
    (object, part) => object?.[part],
    translations[lang]
  );
}

function applyLanguage(language) {
  const lang = translations[language] ? language : "en";
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = translate(lang, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach(element => {
    const value = translate(lang, element.dataset.i18nHtml);
    if (typeof value === "string") element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const value = translate(lang, element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.placeholder = value;
  });

  const switcher = document.getElementById("langSwitch");
  if (switcher) {
    switcher.textContent = lang === "en" ? "EN / CS" : "CS / EN";
    switcher.setAttribute(
      "aria-label",
      lang === "en" ? "Switch to Czech" : "Switch to English"
    );
  }

  document.title = document.title.replace(
    / — DAIKI$/,
    " — DAIKI"
  );

  try {
    localStorage.setItem("daiki-language", lang);
  } catch (error) {
    // Continue without persistent storage.
  }

  window.daikiLanguage = lang;
}

document.addEventListener("DOMContentLoaded", () => {
  let language = "en";

  try {
    language = localStorage.getItem("daiki-language") || "en";
  } catch (error) {
    language = "en";
  }

  applyLanguage(language);

  document.getElementById("langSwitch")?.addEventListener("click", () => {
    applyLanguage(window.daikiLanguage === "en" ? "cs" : "en");
  });
});
